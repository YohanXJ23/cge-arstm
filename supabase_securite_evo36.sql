-- Règles par rubrique : colonnes modifiables, rôles autorisés, nom affiché dans l'historique
create or replace function app_private.table_rules(p_table text, out cols text[], out roles text[], out rubrique text, out required text[])
language plpgsql immutable set search_path = '' as $$
begin
  case p_table
    when 'news' then
      cols := array['visibility','title','date','content','link','link_label']; roles := array['admin'];
      rubrique := 'Actualités'; required := array['title','date','content'];
    when 'jobs' then
      cols := array['title','company','type','description','apply_link']; roles := array['admin'];
      rubrique := 'Emplois & Stages'; required := array['title','company','type'];
    when 'events' then
      cols := array['title','date','description','link','link_label']; roles := array['admin'];
      rubrique := 'Activités'; required := array['title','date'];
    when 'alumni' then
      cols := array['name','promo','role','company','matricule']; roles := array['admin'];
      rubrique := 'Alumni'; required := array['name','promo','role','company'];
    when 'registre' then
      cols := array['image','name','section','promo','status','poste']; roles := array['admin','secretariat'];
      rubrique := 'Registre'; required := array['name','section','promo','status'];
    when 'contacts' then
      cols := array['label','value']; roles := array['admin','secretariat'];
      rubrique := 'Contact'; required := array['label','value'];
    when 'gallery' then
      cols := array['title','category','image']; roles := array['admin','secretariat'];
      rubrique := 'Médiathèque'; required := array['title','category','image'];
    when 'bureau_members' then
      cols := array['matricule','name','role','department','position','bio','image']; roles := array['admin'];
      rubrique := 'Membres du bureau'; required := array['name','role','department'];
    else
      raise exception 'Rubrique inconnue : %', p_table using errcode = '22023';
  end case;
end $$;

-- Contrôle du contenu envoyé (longueurs, liens, photos, valeurs autorisées)
create or replace function app_private.validate_payload(p_table text, p_data jsonb, p_is_insert boolean)
returns void language plpgsql immutable set search_path = '' as $$
declare
  r record; v text; k text;
  rules record;
begin
  select * into rules from app_private.table_rules(p_table);
  foreach k in array rules.required loop
    if (p_is_insert or p_data ? k) and coalesce(btrim(p_data ->> k), '') = '' then
      raise exception 'Le champ « % » est obligatoire.', k using errcode = '22023';
    end if;
  end loop;
  for r in select key, value from jsonb_each(p_data) loop
    if jsonb_typeof(r.value) not in ('string', 'null', 'number') then
      raise exception 'Valeur invalide pour « % ».', r.key using errcode = '22023';
    end if;
    v := r.value #>> '{}';
    continue when v is null or v = '';
    if r.key = 'image' then
      if length(v) > 1500000 then
        raise exception 'La photo est trop lourde (1 Mo maximum après compression).' using errcode = '22023';
      end if;
      if v !~ '^data:image/(jpeg|png|webp|gif);base64,[A-Za-z0-9+/=]+$' and v !~* '^https?://[^\s"<>]+$' then
        raise exception 'Format de photo non accepté.' using errcode = '22023';
      end if;
    elsif r.key in ('content', 'description', 'bio') then
      if length(v) > 10000 then raise exception 'Le texte « % » est trop long (10 000 caractères maximum).', r.key using errcode = '22023'; end if;
    elsif length(v) > 500 then
      raise exception 'Le champ « % » est trop long (500 caractères maximum).', r.key using errcode = '22023';
    end if;
    -- lien web : https:// + vrai nom de domaine (ex. www.exemple.ci), sans espace
    if r.key = 'link' and v !~* '^https?://([a-z0-9-]+\.)+[a-z0-9-]{2,}(:[0-9]{1,5})?([/?#][^\s"<>]*)?$' then
      raise exception 'Le lien n''est pas une adresse web valide (exemple : https://www.exemple.ci).' using errcode = '22023';
    end if;
    if r.key = 'apply_link' and v !~* '^https?://([a-z0-9-]+\.)+[a-z0-9-]{2,}(:[0-9]{1,5})?([/?#][^\s"<>]*)?$'
                           and v !~ '^[^\s@<>"]+@[^\s@<>"]+\.[^\s@<>"]+$' then
      raise exception 'Pour postuler, indiquez un lien https:// ou une adresse email.' using errcode = '22023';
    end if;
    if r.key = 'visibility' and v not in ('public', 'membres') then
      raise exception 'Visibilité inconnue.' using errcode = '22023';
    end if;
    if p_table = 'registre' and r.key = 'status' and v not in ('Membre actuel', 'Ancien membre') then
      raise exception 'Statut inconnu.' using errcode = '22023';
    end if;
    if p_table = 'bureau_members' and r.key = 'position' and v not in ('chef', 'adjoint') then
      raise exception 'Position inconnue (chef ou adjoint).' using errcode = '22023';
    end if;
  end loop;
end $$;

