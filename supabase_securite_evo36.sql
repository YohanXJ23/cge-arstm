-- Petites fonctions de chiffrement (écrites pour fonctionner quel que soit le schéma de pgcrypto)
do $do$
declare s text;
begin
  select n.nspname into s from pg_extension e join pg_namespace n on n.oid = e.extnamespace where e.extname = 'pgcrypto';
  execute format($f$create or replace function app_private.sha256_hex(p text) returns text
    language sql immutable set search_path = '' as $b$ select encode(%I.digest(p, 'sha256'), 'hex') $b$$f$, s);
  execute format($f$create or replace function app_private.bcrypt_hash(p text) returns text
    language sql volatile set search_path = '' as $b$ select %I.crypt(p, %I.gen_salt('bf', 10)) $b$$f$, s, s);
  execute format($f$create or replace function app_private.bcrypt_check(p text, h text) returns boolean
    language sql stable set search_path = '' as $b$ select %I.crypt(p, h) = h $b$$f$, s);
  execute format($f$create or replace function app_private.random_token() returns text
    language sql volatile set search_path = '' as $b$ select encode(%I.gen_random_bytes(32), 'hex') $b$$f$, s);
end $do$;

