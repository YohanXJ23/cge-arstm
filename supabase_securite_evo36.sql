--  À lancer UNE fois dans Supabase > SQL Editor (il peut être relancé sans danger).
--
--  Ce que fait ce script :
--   1. Crée les tables / colonnes manquantes (sans rien supprimer).
--   2. Déplace les mots de passe dans un espace privé, invisible depuis le site :
--      les mots de passe actuels continuent de fonctionner (ils sont convertis en bcrypt
--      à la première connexion). Une copie de sauvegarde est gardée dans app_private.
--   3. Crée les fonctions serveur cge_* utilisées par le site : connexion, sessions,
--      enregistrements, suppressions, J'aime, historique. Chaque fonction vérifie
--      la session et les droits (admin / secrétariat / membre) AVANT d'agir.
--   4. Ferme l'accès direct aux tables : les visiteurs ne peuvent plus que LIRE les
--      rubriques publiques (actualités publiques, activités, médiathèque, contact,
--      bureau sans matricule). Plus aucune écriture directe n'est possible.
--
--  IMPORTANT : ne relancez plus l'ancien script supabase_tout_cge_arstm.sql après celui-ci,
--  il rouvrirait les accès. Mettez en ligne le fichier du site evo36 en même temps.
-- =====================================================================================

