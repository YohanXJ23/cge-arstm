create or replace function app_private.password_matches(p_secret text, p_hash text, p_legacy_id text)
returns boolean language plpgsql stable set search_path = '' as $$
begin
  if p_hash is null or p_secret is null then return false; end if;
  if p_legacy_id is not null then
    -- ancien format du site evo35 : SHA-256 de "cge-arstm-2026|<matricule>|<mot de passe>"
    return p_hash = app_private.sha256_hex('cge-arstm-2026|' || p_legacy_id || '|' || p_secret);
  end if;
  return app_private.bcrypt_check(p_secret, p_hash);
end $$;

create or replace function app_private.check_new_password(p_new text)
returns void language plpgsql immutable set search_path = '' as $$
begin
  if p_new is null or length(btrim(p_new)) < 8 then
    raise exception 'Le mot de passe doit contenir au moins 8 caractères.' using errcode = '22023';
  end if;
  if octet_length(p_new) > 72 then
    raise exception 'Le mot de passe est trop long (72 caractères maximum).' using errcode = '22023';
  end if;
end $$;

create or replace function app_private.session_for(p_token text, p_roles text[] default null)
returns app_private.sessions language plpgsql set search_path = '' as $$
declare s app_private.sessions;
begin
  if p_token is null or p_token !~ '^[0-9a-f]{64}$' then
    raise exception 'Session invalide ou expirée.' using errcode = '28000';
  end if;
  select * into s from app_private.sessions
   where token_hash = app_private.sha256_hex(p_token) and expires_at > now();
  if not found then
    raise exception 'Session invalide ou expirée.' using errcode = '28000';
  end if;
  if p_roles is not null and not (s.role = any (p_roles)) then
    raise exception 'Action non autorisée pour votre compte.' using errcode = '42501';
  end if;
  return s;
end $$;

